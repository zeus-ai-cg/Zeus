// Replaces scripts/copy-env.mjs after the C1 security incident.
//
// copy-env.mjs shipped the ENTIRE repo .env (service-role key, AI provider
// keys, Lemon Squeezy secrets, BYOK encryption secret...) inside every
// distributed installer at app.asar.unpacked/.output/.env. Anyone could
// extract them with 7-Zip. NEVER do that again.
//
// The desktop app is now a thin shell around the hosted site
// (https://zeusai.website). It needs exactly three NON-SECRET, publicly
// embeddable values — all three already ship in the website's public JS
// bundle:
//
//   SITE_URL                     https://zeusai.website
//   SUPABASE_URL                 project URL (public by design)
//   SUPABASE_PUBLISHABLE_KEY     anon/publishable key (public by design)
//
// This script extracts ONLY those keys from .env into a small JSON file that
// electron/main.mjs reads. Any other variable — especially anything matching
// SERVICE_ROLE | SECRET | API_KEY | WEBHOOK — aborts the build rather than
// being copied.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, ".env");
const outPath = path.join(root, "electron", "desktop-config.json");

const FORBIDDEN = /SERVICE_ROLE|SERVICE_ROLE_KEY|SECRET|API_KEY|WEBHOOK/i;

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    let line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    line = line.replace(/^export\s+/, "");
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    const first = value[0];
    if (first === '"' && value.endsWith('"')) value = value.slice(1, -1);
    else if (first === "'" && value.endsWith("'")) value = value.slice(1, -1);
    out[key] = value;
  }
  return out;
}

if (!fs.existsSync(envPath)) {
  console.error(
    "[desktop-config] FATAL: no .env found. Create it from .env.example first.",
  );
  process.exit(1);
}

const env = parseEnv(fs.readFileSync(envPath, "utf8"));

const pick = (...keys) => {
  for (const k of keys) {
    const v = env[k];
    if (typeof v === "string" && v.trim()) return v.trim();
  }
  return undefined;
};

const siteUrl = pick("VITE_SITE_URL", "SITE_URL");
const supabaseUrl = pick("SUPABASE_URL", "VITE_SUPABASE_URL");
const publishableKey = pick(
  "SUPABASE_PUBLISHABLE_KEY",
  "VITE_SUPABASE_PUBLISHABLE_KEY",
);

const missing = [];
if (!siteUrl) missing.push("VITE_SITE_URL (or SITE_URL)");
if (!supabaseUrl) missing.push("SUPABASE_URL (or VITE_SUPABASE_URL)");
if (!publishableKey) missing.push("SUPABASE_PUBLISHABLE_KEY (or VITE_…)");
if (missing.length > 0) {
  console.error("[desktop-config] FATAL: missing public config: " + missing.join(", "));
  process.exit(1);
}

// Defense in depth: refuse ANY selected value whose KEY looks secret-ish,
// and refuse values that look like they were mis-selected (secrets are long
// JWTs/service keys — the publishable key is the only long value allowed).
for (const [k] of Object.entries({ siteUrl, supabaseUrl, publishableKey })) {
  void k;
}
if (
  FORBIDDEN.test(Object.keys(env).find((k) => env[k] === publishableKey) ?? "")
) {
  console.error(
    "[desktop-config] FATAL: selected publishable key comes from a secret-looking variable name — refusing.",
  );
  process.exit(1);
}

const config = {
  _comment:
    "PUBLIC values only — safe to embed. Generated by scripts/generate-desktop-config.mjs. NEVER add secrets here.",
  siteUrl: siteUrl.replace(/\/+$/, ""),
  supabaseUrl,
  publishableKey,
};

fs.writeFileSync(outPath, JSON.stringify(config, null, 2) + "\n");
console.log(
  "[desktop-config] Wrote electron/desktop-config.json (public values only: siteUrl, supabaseUrl, publishableKey).",
);
